import { DOMParser } from '@xmldom/xmldom';

/**
 * Maps XML tag names used in "res/values" files to their Android resource type names.
 * Tags not listed here (e.g. "attr", "declare-styleable") cannot be referenced via
 * "@<type>/<name>" and are not handled by the resource shrinker's keep list.
 */
const VALUES_TAG_TO_RESOURCE_TYPE = {
	array: 'array',
	bool: 'bool',
	color: 'color',
	dimen: 'dimen',
	drawable: 'drawable',
	fraction: 'fraction',
	integer: 'integer',
	'integer-array': 'array',
	plurals: 'plurals',
	string: 'string',
	'string-array': 'array',
	style: 'style'
};

/**
 * Fetches the Android resource type from a "res" subdirectory name by stripping its
 * configuration qualifiers. For example, returns "drawable" for "drawable-land-xhdpi".
 * @param {string} folderName Name of a directory directly under the "res" folder.
 * @returns {string|null} The resource type name, or null if it could not be determined.
 */
export function getResourceTypeFromFolderName(folderName) {
	if (!folderName) {
		return null;
	}
	const resourceType = folderName.split('-')[0].toLowerCase();
	return resourceType || null;
}

/**
 * Creates a "@<type>/<name>" resource reference for a file-based resource such as a
 * drawable, mipmap, raw or xml file. The resource name is the file name up to its
 * first period, which also handles 9-patch file names such as "border.9.png".
 * @param {string} resourceType The resource type name, such as "drawable".
 * @param {string} fileName The resource file's name, such as "background.png".
 * @returns {string|null} The resource reference, or null if the file is not a resource.
 */
export function getFileResourceEntry(resourceType, fileName) {
	if (!resourceType || !fileName || fileName.startsWith('.')) {
		return null;
	}
	const resourceName = fileName.split('.')[0];
	if (!resourceName) {
		return null;
	}
	return `@${resourceType}/${resourceName}`;
}

/**
 * Fetches "@<type>/<name>" resource references for all resources defined by the given
 * "res/values" XML file content, such as strings, colors, styles and arrays.
 * @param {string} xmlContent String content of a "res/values" XML file.
 * @returns {string[]} Array of resource references. Empty if none were found.
 */
export function getValuesResourceEntries(xmlContent) {
	const entries = [];
	if (!xmlContent) {
		return entries;
	}
	const xmlDoc = (new DOMParser()).parseFromString(xmlContent, 'text/xml');
	const rootElement = xmlDoc && xmlDoc.documentElement;
	if (!rootElement || (rootElement.tagName !== 'resources')) {
		return entries;
	}
	for (let index = 0; index < rootElement.childNodes.length; index++) {
		const node = rootElement.childNodes.item(index);
		if (!node || (node.nodeType !== 1)) {  // Element nodes only.
			continue;
		}
		const resourceName = node.getAttribute('name');
		if (!resourceName) {
			continue;
		}
		let resourceType = null;
		if (node.tagName === 'item') {
			// An <item type="drawable" name="x"/> element defines a resource of the given type.
			resourceType = node.getAttribute('type') || null;
		} else {
			resourceType = VALUES_TAG_TO_RESOURCE_TYPE[node.tagName] || null;
		}
		if (resourceType) {
			entries.push(`@${resourceType}/${resourceName}`);
		}
	}
	return entries;
}

/**
 * Generates the content of a resource shrinker "keep" XML file (see the "tools:keep"
 * attribute) from the given resource references. These resources will not be removed
 * when gradle's "shrinkResources" feature is enabled, even if the shrinker cannot see
 * any references to them. This is needed for the app's own resources since Titanium
 * looks them up by name at runtime via reflection (e.g. "TiRHelper" and i18n string
 * lookups), which the resource shrinker cannot detect.
 * @param {string[]} entries Array of "@<type>/<name>" resource references.
 * @returns {string} The keep XML file content.
 */
export function generateKeepXmlContent(entries) {
	const sortedEntries = Array.from(new Set(entries)).sort();
	return [
		'<?xml version="1.0" encoding="utf-8"?>',
		'<!--',
		'\tGenerated by the Titanium build system. Do not edit. Regenerated on every build.',
		'\tKeeps the app\'s own resources when gradle\'s "shrinkResources" feature is enabled,',
		'\tsince Titanium resolves them by name at runtime via reflection which the resource',
		'\tshrinker cannot detect. Resources of libraries (e.g. Material, AppCompat) are not',
		'\tlisted here and can still be shrunk.',
		'-->',
		'<resources xmlns:tools="http://schemas.android.com/tools"',
		'\ttools:keep="' + sortedEntries.join(',') + '" />',
		''
	].join('\n');
}

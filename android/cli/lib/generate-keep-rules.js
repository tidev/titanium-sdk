/** Package that all of the Titanium SDK's kroll module/proxy binding classes live under. */
const SDK_MODULES_PACKAGE = 'ti.modules.titanium';

/**
 * Top-level Titanium namespaces accessed by the SDK's bundled bootstrap scripts
 * ("ti.kernel.js"/"ti.main.js", built from "common/Resources" at SDK build time).
 * Those scripts never run through the app's JavaScript analysis, so their API usage
 * does not show up in "tiSymbols" and their Java classes must always be kept.
 *
 * - App/Filesystem/Locale/Network/Platform/UI: "ti.internal" kernel and extensions.
 * - Android: "ti.internal/kernel/module.js" defines "Ti.Android.currentService".
 * - Codec/Stream/Utils: used by the node.js compatibility shims. (Ti.Buffer and
 *   Ti.API have no Java class. Ti.Buffer lives in the root bindings package which
 *   is always kept and Ti.API is implemented in C++.)
 * - Database/Filesystem/Locale/Media/Platform/UI: namespaces of the "invocation APIs"
 *   registered by the runtime's generated "bootstrap.js" (e.g. "Database.install").
 *   The runtime resolves these namespaces eagerly for every JavaScript scope, so a
 *   stripped one logs a ClassNotFoundException on every app launch.
 */
const BOOTSTRAP_NAMESPACES = [
	'Android', 'App', 'Codec', 'Database', 'Filesystem', 'Locale', 'Media', 'Network', 'Platform', 'Stream', 'UI', 'Utils'
];

/**
 * Fetches all top-level Titanium namespaces (e.g. "UI", "Media") accessed by the app's
 * JavaScript code from the given symbol table produced by the build's JS analysis.
 * @param {Object} tiSymbols Dictionary of JS file paths to arrays of accessed Titanium API names such as "UI.createView".
 * @returns {Set<string>} Set of accessed top-level namespace names.
 */
export function getUsedNamespaces(tiSymbols) {
	const namespaces = new Set();
	for (const file in tiSymbols) {
		const symbolArray = tiSymbols[file];
		if (!symbolArray) {
			continue;
		}
		for (const symbol of symbolArray) {
			if (!symbol) {
				continue;
			}
			const namespace = symbol.split('.')[0];
			if (namespace) {
				namespaces.add(namespace);
			}
		}
	}
	return namespaces;
}

/**
 * Creates a mapping of top-level Titanium namespaces (e.g. "UI") to the SDK's Java
 * packages implementing them (e.g. "ti.modules.titanium.ui") from the SDK's
 * "titanium.bindings.json" file generated by the "kroll-apt" annotation processor.
 *
 * Only modules living directly under a "ti.modules.titanium.<name>" package whose
 * package name matches their API name are top-level modules. This skips submodules
 * such as "Ti.App.Android" ("AndroidModule" in the "app" package) and "Ti.UI.Shortcut"
 * ("ShortcutModule" in the "ui" package), which are covered by their top-level
 * package's keep rule.
 * @param {Object} sdkBindings Parsed content of the SDK's "titanium.bindings.json" file.
 * @returns {Map<string, string>} Mapping of top-level namespace names to Java package names.
 */
export function getSdkNamespacePackages(sdkBindings) {
	const namespaceToPackageMap = new Map();
	const modules = (sdkBindings && sdkBindings.modules) ? sdkBindings.modules : {};
	for (const moduleClassName in modules) {
		if (!moduleClassName.startsWith(SDK_MODULES_PACKAGE + '.')) {
			continue;
		}
		const packageName = moduleClassName.substring(0, moduleClassName.lastIndexOf('.'));
		const relativePackageName = packageName.substring(SDK_MODULES_PACKAGE.length + 1);
		if (!relativePackageName || relativePackageName.includes('.')) {
			continue;
		}
		const apiName = modules[moduleClassName].apiName;
		if (apiName && (relativePackageName === apiName.toLowerCase())) {
			namespaceToPackageMap.set(apiName, packageName);
		}
	}
	return namespaceToPackageMap;
}

/**
 * Generates the content of the "bindings.keep" R8/ProGuard rules file which keeps the
 * Titanium kroll module/proxy binding classes. These classes are resolved by name via
 * JNI by the native V8/Kroll runtime and must not be removed or renamed.
 *
 * By default all binding classes are kept. When "stripUnusedApis" is set, only the
 * classes of the SDK modules actually accessed by the app's JavaScript code (plus the
 * ones needed by the SDK's bootstrap scripts) are kept, so R8 can remove the unused
 * SDK modules (e.g. Ti.Calendar, Ti.Contacts, Ti.Media) from the app. This is safe
 * because the runtime resolves bindings lazily; a binding that is never accessed from
 * JavaScript is never looked up via JNI. Native module classes are always fully kept
 * since their bundled JavaScript is not guaranteed to be analyzed.
 * @param {Object} options Parameters used to generate the keep rules.
 * @param {Object} [options.tiSymbols] Dictionary of JS file paths to arrays of accessed Titanium API names.
 * @param {Object} [options.sdkBindings] Parsed content of the SDK's "titanium.bindings.json" file.
 * @param {Object[]} [options.moduleBindingsList] Array of parsed bindings JSON objects from native modules.
 * @param {boolean} [options.stripUnusedApis] Set true to only keep the Titanium APIs used by the app.
 * @returns {{content: string, keptNamespaces: string[], strippedNamespaces: string[], unresolvedNamespaces: string[]}}
 *          The keep rule file content and namespace info for logging purposes.
 */
export function generateBindingsKeepRules(options) {
	const tiSymbols = options.tiSymbols || {};
	const sdkBindings = options.sdkBindings;
	const moduleBindingsList = options.moduleBindingsList || [];
	const stripUnusedApis = !!options.stripUnusedApis;

	const lines = [
		'# Generated by the Titanium build system. Do not edit. This file is regenerated on every build.',
		'#',
		'# Keeps the Kroll module/proxy binding classes, which the native V8/Kroll runtime',
		'# resolves by name via JNI. (See the "titanium.keep" file in this folder.)',
		''
	];

	if (!stripUnusedApis || !sdkBindings || !sdkBindings.modules) {
		lines.push(
			'# All Titanium SDK binding classes are kept. Set the "android.optimization.stripUnusedApis"',
			'# tiapp property to true to only keep the APIs used by the app\'s JavaScript code.',
			'-keep class ti.modules.** { *; }',
			'-keep interface ti.modules.** { *; }',
			'',
			'# Kroll proxies and modules of native Titanium modules live in their own packages,',
			'# but always derive from this base type and are resolved by name through their',
			'# generated C++ bindings.',
			'-keep class * extends org.appcelerator.kroll.KrollProxy { *; }',
			''
		);
		return {
			content: lines.join('\n'),
			keptNamespaces: [],
			strippedNamespaces: [],
			unresolvedNamespaces: []
		};
	}

	// Determine which top-level SDK namespaces must be kept.
	const namespaceToPackageMap = getSdkNamespacePackages(sdkBindings);
	const usedNamespaces = getUsedNamespaces(tiSymbols);
	for (const namespace of BOOTSTRAP_NAMESPACES) {
		usedNamespaces.add(namespace);
	}
	const keptNamespaces = [];
	const unresolvedNamespaces = [];
	for (const namespace of usedNamespaces) {
		if (namespaceToPackageMap.has(namespace)) {
			keptNamespaces.push(namespace);
		} else {
			// No matching SDK Java package. This is either implemented natively in C++
			// (e.g. Ti.API), lives outside "ti.modules" and is kept via "titanium.keep"
			// (e.g. Ti.Blob), or is provided by a native module which is fully kept below.
			unresolvedNamespaces.push(namespace);
		}
	}
	keptNamespaces.sort();
	unresolvedNamespaces.sort();
	const strippedNamespaces = Array.from(namespaceToPackageMap.keys())
		.filter(namespace => !usedNamespaces.has(namespace))
		.sort();

	lines.push(
		'# Only the SDK modules used by the app\'s JavaScript code and the SDK\'s bootstrap',
		'# scripts are kept. ("android.optimization.stripUnusedApis" tiapp property is true.)',
		'# If the app accesses Titanium APIs dynamically (e.g. via Ti[name]) the build cannot',
		'# detect them. Add keep rules for them to the app\'s "platform/android/proguard.cfg".',
		stripUnusedNamespacesComment('Stripped unused SDK modules', strippedNamespaces),
		'',
		'# Classes in the SDK\'s root bindings package. (TitaniumModule, BufferProxy, etc.)',
		`-keep class ${SDK_MODULES_PACKAGE}.* { *; }`,
		''
	);
	for (const namespace of keptNamespaces) {
		lines.push(`# Ti.${namespace}`);
		lines.push(`-keep class ${namespaceToPackageMap.get(namespace)}.** { *; }`);
	}
	lines.push(
		'',
		'# Kroll proxies outside of the SDK\'s "ti.modules" packages. (Native Titanium modules',
		'# and custom proxy classes.) These are always resolved by name via JNI, so keep them all.',
		'-keep class !ti.modules.**,** extends org.appcelerator.kroll.KrollProxy { *; }',
		''
	);

	// Keep all binding classes of the app's native modules, in case the above
	// "extends" rule misses one. (e.g. A module class not deriving from KrollProxy.)
	const moduleClassNames = new Set();
	for (const moduleBindings of moduleBindingsList) {
		for (const sectionName of [ 'modules', 'proxies' ]) {
			for (const className in (moduleBindings[sectionName] || {})) {
				if (!className.startsWith('org.appcelerator.') && !className.startsWith(SDK_MODULES_PACKAGE + '.')) {
					moduleClassNames.add(className);
				}
			}
		}
	}
	if (moduleClassNames.size > 0) {
		lines.push('# Java binding classes of the native Titanium modules used by this app.');
		for (const className of Array.from(moduleClassNames).sort()) {
			lines.push(`-keep class ${className} { *; }`);
		}
		lines.push('');
	}

	return {
		content: lines.join('\n'),
		keptNamespaces,
		strippedNamespaces,
		unresolvedNamespaces
	};
}

/**
 * Creates a "#" comment line listing the given namespaces, or stating none were found.
 * @param {string} title Text to prefix the namespace listing with.
 * @param {string[]} namespaces Array of namespace names. Can be empty.
 * @returns {string} The comment line.
 */
function stripUnusedNamespacesComment(title, namespaces) {
	if (namespaces.length <= 0) {
		return `# ${title}: (none)`;
	}
	return `# ${title}: ${namespaces.map(namespace => 'Ti.' + namespace).join(', ')}`;
}
